  const cache = {};

  function get(shape, element) {
    const rows = SHAPES[shape];
    if (!rows) return null;
    const tint = TINTS[element] || TINTS.fire;
    const key = shape + ':' + (TINTS[element] ? element : 'fire');
    if (!cache[key]) {
      cache[key] = A.makeSprite(rows, { A: tint[0], B: tint[1], C: tint[2] }, FX_D);
    }
    return cache[key];
  }

  DS.FXArt = {
    D: FX_D,
    shapes: SHAPES,
    tints: TINTS,
    get: get,
    has: function (shape) { return !!SHAPES[shape]; }
  };
