/* Elemental particle shapes.

   Every effect used to be the same square dot in a different colour, so fire,
   poison and earth all read identically once they were moving. These are small
   named silhouettes -- a flame licks, a shard is angular, a bubble is round
   with a highlight, a leaf has a stem -- and the emitters in elements.js pair
   each one with motion that matches it.

   Authored at 2x detail. `DS.FXArt.get(shape, element)` returns a baked sprite;
   everything is built once at load, so the render loop never bakes.

   Generated by tools/art/fx.py -- edit the generator, not this file. */
